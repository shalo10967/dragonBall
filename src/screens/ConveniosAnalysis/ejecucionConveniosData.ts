  // Función helper para formatear valores monetarios
  export const formatCurrency = (value: number): string => {
    return new Intl.NumberFormat('es-CO', {
      style: 'currency',
      currency: 'COP',
      minimumFractionDigits: 0,
    }).format(value);
  };
  
  // Función helper para obtener estadísticas
export const getEjecucionStats = () => {
    const total = ejecucionConveniosData.length;
    const totalEjecutado = ejecucionConveniosData.reduce((sum, convenio) => sum + convenio.valorEjecutado, 0);
    const municipios = Array.from(new Set(ejecucionConveniosData.map(c => c.municipio)));
    
    return {
        total,
        totalEjecutado,
        municipios: municipios.length,
        municipiosList: municipios
    };
};
